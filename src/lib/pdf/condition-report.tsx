import { Document, Page, View, Text, Image, Svg, Path } from "@react-pdf/renderer";
import { styles, BRASS } from "./styles";
import type { ReportPropertyInfo, ReportRoom } from "./types";

function Watermark() {
  return (
    <Text style={styles.watermark} fixed>
      PREVIEW — UNLOCK TO REMOVE
    </Text>
  );
}

function SealMark() {
  return (
    <Svg width={22} height={22} viewBox="0 0 24 24">
      <Path
        d="M12 2 4 5v6c0 5 3.5 8.5 8 10 4.5-1.5 8-5 8-10V5l-8-3Z"
        stroke={BRASS}
        strokeWidth={1.6}
        fill="none"
      />
      <Path d="m9 12 2 2 4-4" stroke={BRASS} strokeWidth={1.6} fill="none" />
    </Svg>
  );
}

function Footer({ label }: { label: string }) {
  return (
    <View style={styles.pageFooter} fixed>
      <Text>Deposit Shield · {label}</Text>
      <Text render={({ pageNumber, totalPages }) => `Page ${pageNumber} of ${totalPages}`} />
    </View>
  );
}

export function CoverPage({
  title,
  property,
  watermark,
}: {
  title: string;
  property: ReportPropertyInfo;
  watermark: boolean;
}) {
  return (
    <Page size="A4" style={styles.coverPage}>
      {watermark && <Watermark />}
      <View style={styles.row}>
        <SealMark />
        <Text style={{ marginLeft: 8, fontFamily: "Times-Roman", fontSize: 14 }}>Deposit Shield</Text>
      </View>

      <View>
        <Text style={{ fontSize: 10, color: BRASS, marginBottom: 10, letterSpacing: 2 }}>
          {title.toUpperCase()}
        </Text>
        <Text style={styles.h1}>{property.displayName}</Text>
        {property.addressLines.map((line) => (
          <Text key={line} style={{ fontSize: 11, marginTop: 2, color: "#d7dbe2" }}>{line}</Text>
        ))}

        <View style={{ marginTop: 28, borderTopWidth: 1, borderTopColor: "#2a3650", paddingTop: 20 }}>
          <Row label="Prepared for" value={property.tenantEmail} />
          <Row label="Date" value={property.dateLabel} />
          <Row label="Security deposit" value={property.depositAmountLabel} />
          {property.stateName && property.stateDeadlineDays && (
            <Row
              label="Return deadline"
              value={`${property.stateDeadlineDays} days after move-out (${property.stateName})`}
            />
          )}
        </View>
      </View>

      <Text style={{ fontSize: 8, color: "#8c94a6" }}>
        Generated by Deposit Shield. Documentation tool only — not legal advice.
      </Text>
    </Page>
  );
}

function Row({ label, value }: { label: string; value: string }) {
  return (
    <View style={{ flexDirection: "row", justifyContent: "space-between", marginBottom: 8, width: 320 }}>
      <Text style={{ color: "#9099b0" }}>{label}</Text>
      <Text style={{ color: "#fff", fontFamily: "Courier", fontSize: 9 }}>{value}</Text>
    </View>
  );
}

export function RoomPage({
  room,
  phaseLabel,
  watermark,
}: {
  room: ReportRoom;
  phaseLabel: string;
  watermark: boolean;
}) {
  return (
    <Page size="A4" style={styles.page} wrap>
      {watermark && <Watermark />}
      <View style={styles.pageHeader} fixed>
        <Text style={styles.h3}>{room.name}</Text>
        <Text style={styles.small}>{phaseLabel}</Text>
      </View>
      {room.photos.length === 0 ? (
        <Text style={styles.small}>No photos captured for this room.</Text>
      ) : (
        <View style={styles.wrap}>
          {room.photos.map((photo, i) => (
            <View key={i} style={styles.photoCard} wrap={false}>
              <Image src={photo.url} style={styles.photoImage} />
              <Text style={{ fontSize: 8, marginBottom: 1 }}>
                {new Date(photo.capturedAt).toLocaleString("en-US")}
              </Text>
              <Text style={{ fontSize: 8, marginBottom: 1, textTransform: "capitalize" }}>
                Condition: {photo.condition}
              </Text>
              {photo.note && <Text style={{ fontSize: 8, marginBottom: 1 }}>{photo.note}</Text>}
              <Text style={{ fontSize: 6.5, fontFamily: "Courier", color: "#8c94a6" }}>
                {photo.sha256.slice(0, 16)}…
              </Text>
            </View>
          ))}
        </View>
      )}
      <Footer label={phaseLabel} />
    </Page>
  );
}

export function IntegrityAppendixPage({ label }: { label: string }) {
  return (
    <Page size="A4" style={styles.page}>
      <View style={styles.pageHeader}>
        <Text style={styles.h3}>Integrity appendix</Text>
        <Text style={styles.small}>{label}</Text>
      </View>
      <Text style={{ marginBottom: 10, lineHeight: 1.5 }}>
        Every photo in this report was fingerprinted the moment it was captured, using a cryptographic
        function called SHA-256. Think of it as a tamper-evident seal: the fingerprint is calculated from
        the exact bytes of the photo, so if even a single pixel changed after capture, the fingerprint
        would be completely different.
      </Text>
      <Text style={{ marginBottom: 10, lineHeight: 1.5 }}>
        Each photo page in this report shows a truncated version of that fingerprint beneath the image.
        The full fingerprint is stored alongside the capture timestamp at the moment the photo was taken,
        before it was uploaded anywhere — this is what makes the record trustworthy as evidence, rather
        than just a photo album.
      </Text>
      <Text style={{ marginBottom: 10, lineHeight: 1.5 }}>
        If a landlord or a court disputes the authenticity of a photo, the original file can be
        re-hashed and compared against the fingerprint recorded at capture time to confirm nothing has
        been altered.
      </Text>
      <View style={styles.divider} />
      <Text style={{ fontSize: 9, color: "#5b6472" }}>
        This report is a documentation aid. It does not constitute legal advice, and Deposit Shield is
        not a law firm. Consult your state housing authority or an attorney for guidance specific to your
        situation.
      </Text>
      <Footer label="Integrity appendix" />
    </Page>
  );
}

export function SignaturePage({ label }: { label: string }) {
  return (
    <Page size="A4" style={styles.page}>
      <View style={styles.pageHeader}>
        <Text style={styles.h3}>Acknowledgment</Text>
        <Text style={styles.small}>{label}</Text>
      </View>
      <Text style={{ marginBottom: 40, lineHeight: 1.5 }}>
        The undersigned confirms that the photographs and notes in this report accurately reflect the
        condition of the property on the date indicated above.
      </Text>

      <SignatureLine label="Tenant signature" />
      <SignatureLine label="Landlord / property manager signature (optional)" />

      <Footer label="Acknowledgment" />
    </Page>
  );
}

function SignatureLine({ label }: { label: string }) {
  return (
    <View style={{ marginBottom: 36 }}>
      <View style={{ borderBottomWidth: 1, borderBottomColor: "#0b1220", height: 40 }} />
      <View style={{ flexDirection: "row", justifyContent: "space-between", marginTop: 4 }}>
        <Text style={{ fontSize: 8, color: "#5b6472" }}>{label}</Text>
        <Text style={{ fontSize: 8, color: "#5b6472" }}>Date: ______________</Text>
      </View>
    </View>
  );
}

export function ConditionReportDocument({
  title,
  phaseLabel,
  property,
  rooms,
  watermark,
}: {
  title: string;
  phaseLabel: string;
  property: ReportPropertyInfo;
  rooms: ReportRoom[];
  watermark: boolean;
}) {
  return (
    <Document title={`Deposit Shield — ${title}`}>
      <CoverPage title={title} property={property} watermark={watermark} />
      {rooms.map((room) => (
        <RoomPage key={room.name} room={room} phaseLabel={phaseLabel} watermark={watermark} />
      ))}
      <IntegrityAppendixPage label={phaseLabel} />
      <SignaturePage label={phaseLabel} />
    </Document>
  );
}
